import React, { useState, useEffect } from 'react'
import JSZip from 'jszip'
import {
  X,
  Download,
  UploadCloud,
  FileCode,
  Layers,
  Code2,
  FileText,
  ExternalLink,
  CheckCircle2,
  Terminal,
  Globe,
} from 'lucide-react'

export const ExportModal = ({
  isOpen,
  onClose,
  html = '',
  css = '',
  js = '',
  projectName = 'forma-website',
  prompt = 'AI Generated Website',
}) => {
  const [activeTab, setActiveTab] = useState('download') // 'download' | 'deploy'
  const [isZipping, setIsZipping] = useState(false)
  const [downloadSuccess, setDownloadSuccess] = useState(false)

  // Close on Escape key
  useEffect(() => {
    const handleKeyDown = (e) => {
      if (e.key === 'Escape' && isOpen) onClose?.()
    }
    window.addEventListener('keydown', handleKeyDown)
    return () => window.removeEventListener('keydown', handleKeyDown)
  }, [isOpen, onClose])

  if (!isOpen) return null

  // Generate and download .zip archive using JSZip
  const handleDownloadZip = async () => {
    setIsZipping(true)
    setDownloadSuccess(false)

    try {
      const ZipClass = JSZip?.default || JSZip
      const zip = new ZipClass()

      const finalHtml =
        html && html.trim()
          ? html
          : `<!DOCTYPE html><html><head><title>${projectName}</title><link rel="stylesheet" href="style.css"></head><body><h1>${prompt}</h1><script src="script.js"></script></body></html>`

      const finalCss =
        css && css.trim()
          ? css
          : `/* Generated by FORMA */\nbody { font-family: sans-serif; background: #09090b; color: #fff; }`

      const finalJs =
        js && js.trim()
          ? js
          : `// Generated by FORMA\nconsole.log('Website initialized');`

      const readmeContent = `# ${projectName}

> Generated by **FORMA** — Give thought its form.
> Prompt: "${prompt}"

## Files Included
- \`index.html\` — Semantic HTML5 markup
- \`style.css\` — Custom styles & Tailwind utilities
- \`script.js\` — Interactive DOM behaviors

## How to Run Locally
1. Unzip the folder.
2. Double click \`index.html\` to open directly in any modern browser.
3. Or serve with any local HTTP server:
   \`\`\`bash
   npx serve .
   \`\`\`

## Deployment
- **Netlify**: Drag & drop this unzipped folder into [Netlify Drop](https://app.netlify.com/drop).
- **Vercel**: Run \`npx vercel deploy\` in this directory.
`

      zip.file('index.html', finalHtml)
      zip.file('style.css', finalCss)
      zip.file('script.js', finalJs)
      zip.file('README.md', readmeContent)

      const blob = await zip.generateAsync({ type: 'blob' })
      const url = URL.createObjectURL(blob)
      const a = document.createElement('a')
      a.href = url
      a.download = `${projectName.toLowerCase().replace(/\s+/g, '-')}.zip`
      document.body.appendChild(a)
      a.click()
      document.body.removeChild(a)
      URL.revokeObjectURL(url)

      setDownloadSuccess(true)
      setTimeout(() => setDownloadSuccess(false), 4000)
    } catch (err) {
      console.error('Failed to create zip:', err)
    } finally {
      setIsZipping(false)
    }
  }

  // Individual file download
  const handleDownloadSingle = (filename, content, mime) => {
    const blob = new Blob([content], { type: mime })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = filename
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fadeIn font-sans text-left">
      <div
        className="w-full max-w-2xl rounded-3xl bg-[#0f0f14] border border-[rgba(244,240,232,0.12)] p-6 sm:p-8 shadow-2xl flex flex-col gap-6 relative"
        onClick={(e) => e.stopPropagation()}
        role="dialog"
        aria-modal="true"
        aria-label="Export and Deploy website"
      >
        {/* Header */}
        <div className="flex items-center justify-between pb-4 border-b border-[rgba(244,240,232,0.08)]">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-[#ff6326]/10 border border-[#ff6326]/30 flex items-center justify-center text-[#ff6326]">
              <UploadCloud className="w-5 h-5" />
            </div>
            <div className="flex flex-col">
              <h2 className="text-lg sm:text-xl font-bold text-white font-display">
                Export &amp; Deploy Website
              </h2>
              <span className="text-xs text-[#9c978e]">
                Download production-ready source code or deploy to the cloud
              </span>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-[#9c978e] hover:text-white hover:bg-white/5 transition-colors cursor-pointer"
            aria-label="Close modal"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Tab Navigation */}
        <div className="flex items-center gap-2 p-1 rounded-xl bg-[#09090b] border border-[rgba(244,240,232,0.06)] w-fit">
          <button
            type="button"
            onClick={() => setActiveTab('download')}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
              activeTab === 'download'
                ? 'bg-[#ff6326] text-white shadow-sm'
                : 'text-[#9c978e] hover:text-[#fbf9f5]'
            }`}
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download .ZIP</span>
          </button>

          <button
            type="button"
            onClick={() => setActiveTab('deploy')}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
              activeTab === 'deploy'
                ? 'bg-[#ff6326] text-white shadow-sm'
                : 'text-[#9c978e] hover:text-[#fbf9f5]'
            }`}
          >
            <Globe className="w-3.5 h-3.5" />
            <span>Deploy Integrations</span>
          </button>
        </div>

        {/* Tab 1: Download .zip */}
        {activeTab === 'download' && (
          <div className="flex flex-col gap-5 animate-fadeIn">
            {/* Manifest List */}
            <div className="flex flex-col gap-2">
              <span className="text-[11px] font-mono uppercase tracking-wider text-[#635f58] font-semibold">
                Bundle Manifest (4 Files)
              </span>

              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
                <div className="p-3 rounded-xl bg-[#14141a] border border-[rgba(244,240,232,0.06)] flex items-center justify-between">
                  <div className="flex items-center gap-2.5">
                    <FileCode className="w-4 h-4 text-rose-400" />
                    <div className="flex flex-col">
                      <span className="text-xs font-mono font-semibold text-white">index.html</span>
                      <span className="text-[10px] text-[#9c978e]">Document Structure</span>
                    </div>
                  </div>
                  <button
                    type="button"
                    onClick={() => handleDownloadSingle('index.html', html, 'text/html')}
                    className="text-[11px] text-[#ff6326] hover:underline cursor-pointer"
                  >
                    Download
                  </button>
                </div>

                <div className="p-3 rounded-xl bg-[#14141a] border border-[rgba(244,240,232,0.06)] flex items-center justify-between">
                  <div className="flex items-center gap-2.5">
                    <Layers className="w-4 h-4 text-cyan-400" />
                    <div className="flex flex-col">
                      <span className="text-xs font-mono font-semibold text-white">style.css</span>
                      <span className="text-[10px] text-[#9c978e]">Stylesheet &amp; Themes</span>
                    </div>
                  </div>
                  <button
                    type="button"
                    onClick={() => handleDownloadSingle('style.css', css, 'text/css')}
                    className="text-[11px] text-[#ff6326] hover:underline cursor-pointer"
                  >
                    Download
                  </button>
                </div>

                <div className="p-3 rounded-xl bg-[#14141a] border border-[rgba(244,240,232,0.06)] flex items-center justify-between">
                  <div className="flex items-center gap-2.5">
                    <Code2 className="w-4 h-4 text-amber-400" />
                    <div className="flex flex-col">
                      <span className="text-xs font-mono font-semibold text-white">script.js</span>
                      <span className="text-[10px] text-[#9c978e]">Interactivity Scripts</span>
                    </div>
                  </div>
                  <button
                    type="button"
                    onClick={() => handleDownloadSingle('script.js', js, 'application/javascript')}
                    className="text-[11px] text-[#ff6326] hover:underline cursor-pointer"
                  >
                    Download
                  </button>
                </div>

                <div className="p-3 rounded-xl bg-[#14141a] border border-[rgba(244,240,232,0.06)] flex items-center justify-between">
                  <div className="flex items-center gap-2.5">
                    <FileText className="w-4 h-4 text-[#9c978e]" />
                    <div className="flex flex-col">
                      <span className="text-xs font-mono font-semibold text-white">README.md</span>
                      <span className="text-[10px] text-[#9c978e]">Deployment Guide</span>
                    </div>
                  </div>
                  <span className="text-[10px] text-[#635f58] font-mono">Included</span>
                </div>
              </div>
            </div>

            {/* Primary Download Button */}
            <div className="pt-3 border-t border-[rgba(244,240,232,0.06)] flex flex-col sm:flex-row items-center justify-between gap-3">
              <div className="text-xs text-[#9c978e]">
                {downloadSuccess ? (
                  <span className="inline-flex items-center gap-1.5 text-emerald-400 font-medium">
                    <CheckCircle2 className="w-4 h-4" />
                    Archive downloaded successfully!
                  </span>
                ) : (
                  <span>Ready to unpack and run on any browser or server.</span>
                )}
              </div>

              <button
                type="button"
                disabled={isZipping}
                onClick={handleDownloadZip}
                className="w-full sm:w-auto px-6 py-3 rounded-xl text-xs sm:text-sm font-bold bg-[#ff6326] hover:bg-[#ff7a45] active:bg-[#e0551e] text-white flex items-center justify-center gap-2 shadow-xl shadow-[#ff6326]/20 transition-all cursor-pointer disabled:opacity-50"
              >
                {isZipping ? (
                  <>
                    <span className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin inline-block" />
                    <span>Packaging ZIP...</span>
                  </>
                ) : (
                  <>
                    <Download className="w-4 h-4" />
                    <span>Download .zip Package</span>
                  </>
                )}
              </button>
            </div>
          </div>
        )}

        {/* Tab 2: Deploy Integrations */}
        {activeTab === 'deploy' && (
          <div className="flex flex-col gap-4 animate-fadeIn">
            {/* Vercel Integration Card */}
            <div className="p-4 sm:p-5 rounded-2xl bg-[#14141a] border border-[rgba(244,240,232,0.08)] flex flex-col gap-3">
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-3">
                  <div className="w-8 h-8 rounded-lg bg-black border border-white/20 flex items-center justify-center text-white">
                    <svg viewBox="0 0 24 24" fill="currentColor" className="w-4 h-4">
                      <path d="M12 2L2 20h20L12 2z" />
                    </svg>
                  </div>
                  <div className="flex flex-col">
                    <h3 className="text-sm font-bold text-white">Deploy to Vercel</h3>
                    <span className="text-[11px] text-[#9c978e]">Instant serverless deployment with automatic HTTPS</span>
                  </div>
                </div>

                <a
                  href="https://vercel.com/new"
                  target="_blank"
                  rel="noopener noreferrer"
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-white text-black hover:bg-neutral-200 transition-colors"
                >
                  <span>Open Vercel</span>
                  <ExternalLink className="w-3 h-3" />
                </a>
              </div>

              {/* CLI Instruction Box */}
              <div className="p-3 rounded-xl bg-[#09090b] border border-white/5 flex items-center justify-between font-mono text-xs text-[#dcd7ce]">
                <div className="flex items-center gap-2">
                  <Terminal className="w-3.5 h-3.5 text-[#ff6326]" />
                  <span>npx vercel deploy</span>
                </div>
                <span className="text-[10px] text-[#635f58]">CLI</span>
              </div>
            </div>

            {/* Netlify Integration Card */}
            <div className="p-4 sm:p-5 rounded-2xl bg-[#14141a] border border-[rgba(244,240,232,0.08)] flex flex-col gap-3">
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-3">
                  <div className="w-8 h-8 rounded-lg bg-[#00ad9f]/20 border border-[#00ad9f]/40 flex items-center justify-center text-[#00ad9f]">
                    <Globe className="w-4 h-4" />
                  </div>
                  <div className="flex flex-col">
                    <h3 className="text-sm font-bold text-white">Deploy to Netlify (Drag &amp; Drop)</h3>
                    <span className="text-[11px] text-[#9c978e]">Drop the downloaded .zip into Netlify Drop for instant live URL</span>
                  </div>
                </div>

                <a
                  href="https://app.netlify.com/drop"
                  target="_blank"
                  rel="noopener noreferrer"
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-[#00ad9f] text-white hover:bg-[#00c4b4] transition-colors"
                >
                  <span>Netlify Drop</span>
                  <ExternalLink className="w-3 h-3" />
                </a>
              </div>

              {/* CLI Instruction Box */}
              <div className="p-3 rounded-xl bg-[#09090b] border border-white/5 flex items-center justify-between font-mono text-xs text-[#dcd7ce]">
                <div className="flex items-center gap-2">
                  <Terminal className="w-3.5 h-3.5 text-[#00ad9f]" />
                  <span>npx netlify deploy --prod</span>
                </div>
                <span className="text-[10px] text-[#635f58]">CLI</span>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  )
}
